func TestValidateFleetctlRedirectURI(t *testing.T) {
	for _, uri := range []string{
		"http://127.0.0.1:8080/callback",
		"http://127.0.0.5:1/callback",
		"http://[::1]:65535/callback",
	} {
		require.NoError(t, ValidateFleetctlRedirectURI(uri), uri)
	}
	for _, uri := range []string{
		"",
		"https://127.0.0.1:8080/callback",
		"http://localhost:8080/callback",
		"http://example.com:8080/callback",
		"http://10.0.0.1:8080/callback",
		"http://127.0.0.1/callback",
		"http://127.0.0.1:8080/",
		"http://127.0.0.1:8080/callback/x",
		"http://127.0.0.1:8080/callback?x=1",
		"http://127.0.0.1:8080/callback#x",
		"http://user@127.0.0.1:8080/callback",
		"javascript:alert(1)",
	} {
		require.Error(t, ValidateFleetctlRedirectURI(uri), uri)
	}
}

func TestFleetctlCodeChallenge(t *testing.T) {
	// Test vector from RFC 7636 appendix B.
	verifier := "dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk"
	challenge := "E9Melhoa2OwvFrEMTJguCHaoeK1t8URWbuGJSstw-cM"

	require.NoError(t, ValidateFleetctlCodeChallenge(challenge))
	assert.True(t, VerifyFleetctlCodeVerifier(challenge, verifier))
	assert.False(t, VerifyFleetctlCodeVerifier(challenge, verifier[:len(verifier)-1]+"l"))
	assert.False(t, VerifyFleetctlCodeVerifier(challenge, ""))
	// Plain (non-hashed) challenges are rejected.
	assert.False(t, VerifyFleetctlCodeVerifier(verifier, verifier))

	require.Error(t, ValidateFleetctlCodeChallenge(""))
	require.Error(t, ValidateFleetctlCodeChallenge(challenge+"="))
	require.Error(t, ValidateFleetctlCodeChallenge(strings.Repeat("a", 43)+"!"))
}

func TestFleetctlVerificationCode(t *testing.T) {
	code := FleetctlVerificationCode("challenge")
	assert.Regexp(t, `^[BCDFGHJKLMNPQRSTVWXZ]{4}-[BCDFGHJKLMNPQRSTVWXZ]{4}$`, code)
	assert.Equal(t, code, FleetctlVerificationCode("challenge"))
	assert.NotEqual(t, code, FleetctlVerificationCode("other-challenge"))
}

func TestFleetctlStore(t *testing.T) {
	pool := redistest.SetupRedis(t, "sso:fleetctl:", false, false, false)
	store := NewSessionStore(pool)

	t.Run("request", func(t *testing.T) {
		sessionID, err := generateSessionID()
		require.NoError(t, err)

		got, err := store.ConsumeFleetctlRequest(sessionID)
		require.NoError(t, err)
		assert.Nil(t, got)

		req := FleetctlRequest{RedirectURI: "http://127.0.0.1:1234/callback", State: "state", CodeChallenge: "challenge"}
		require.NoError(t, store.CreateFleetctlRequest(sessionID, req, 60))
		got, err = store.ConsumeFleetctlRequest(sessionID)
		require.NoError(t, err)
		assert.Equal(t, &req, got)

		// Single use.
		got, err = store.ConsumeFleetctlRequest(sessionID)
		require.NoError(t, err)
		assert.Nil(t, got)

		// Session IDs not generated by Fleet are never looked up.
		require.Error(t, store.CreateFleetctlRequest("not-a-session-id", req, 60))
		got, err = store.ConsumeFleetctlRequest("not-a-session-id")
		require.NoError(t, err)
		assert.Nil(t, got)
	})

	t.Run("consent", func(t *testing.T) {
		_, err := store.ConsumeFleetctlConsent("missing")
		require.ErrorIs(t, err, ErrSessionNotFound)

		data := FleetctlConsent{
			UserID:        42,
			Email:         "a@example.com",
			RedirectURI:   "http://127.0.0.1:1234/callback",
			State:         "state",
			CodeChallenge: "challenge",
		}
		require.NoError(t, store.CreateFleetctlConsent("the-consent", data))
		got, err := store.ConsumeFleetctlConsent("the-consent")
		require.NoError(t, err)
		assert.Equal(t, &data, got)

		_, err = store.ConsumeFleetctlConsent("the-consent")
		require.ErrorIs(t, err, ErrSessionNotFound)
	})

	t.Run("code", func(t *testing.T) {
		_, err := store.ConsumeFleetctlCode("missing")
		require.ErrorIs(t, err, ErrSessionNotFound)

		data := FleetctlCode{UserID: 42, RedirectURI: "http://127.0.0.1:1234/callback", CodeChallenge: "challenge"}
		require.NoError(t, store.CreateFleetctlCode("the-code", data))

		// The code itself is not stored in Redis.
		conn := pool.Get()
		defer conn.Close()
		sum := sha256.Sum256([]byte("the-code"))
		exists, err := conn.Do("EXISTS", fleetctlCodeKeyPrefix+base64.RawURLEncoding.EncodeToString(sum[:]))
		require.NoError(t, err)
		require.EqualValues(t, 1, exists)

		// Concurrent redemptions: exactly one wins.
		var wg sync.WaitGroup
		var mu sync.Mutex
		var wins int
		for range 10 {
			wg.Go(func() {
				got, err := store.ConsumeFleetctlCode("the-code")
				if err == nil {
					mu.Lock()
					wins++
					mu.Unlock()
					assert.Equal(t, &data, got)
				} else {
					assert.ErrorIs(t, err, ErrSessionNotFound)
				}
			})
		}
		wg.Wait()
		assert.Equal(t, 1, wins)
	})
}
